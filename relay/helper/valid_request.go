func GetAndValidOpenAIImageRequest(c gin.Context, relayMode int) (*dto.ImageRequest, error) {
	imageRequest := &dto.ImageRequest{}

	switch relayMode {
	case relayconstant.RelayModeImagesEdits:
		if strings.Contains(c.Request().Header.Get("Content-Type"), "multipart/form-data") {
			_, err := c.MultipartForm()
			if err != nil {
				return nil, fmt.Errorf("failed to parse image edit form request: %w", err)
			}
			formData := c.Request().PostForm
			imageRequest.Prompt = formData.Get("prompt")
			imageRequest.Model = formData.Get("model")
			if n := common.String2Int(formData.Get("n")); n > 0 {
				imageRequest.N = lo.ToPtr(uint(n))
			}
			imageRequest.Quality = formData.Get("quality")
			imageRequest.Size = formData.Get("size")
			if imageValue := formData.Get("image"); imageValue != "" {
				imageRequest.Image, _ = json.Marshal(imageValue)
			}

			if imageRequest.Model == "gpt-image-1" {
				if imageRequest.Quality == "" {
					imageRequest.Quality = "standard"
				}
			}
			if lo.FromPtrOr(imageRequest.N, 0) == 0 {
				imageRequest.N = lo.ToPtr(uint(1))
			}

			hasWatermark := formData.Has("watermark")
			if hasWatermark {
				watermark := formData.Get("watermark") == "true"
				imageRequest.Watermark = &watermark
			}
			break
		}
		fallthrough
	default:
		err := common.UnmarshalBodyReusable(c, imageRequest)
		if err != nil {
			return nil, err
		}

		if imageRequest.Model == "" {
			//imageRequest.Model = "dall-e-3"
			return nil, errors.New("model is required")
		}

		if strings.Contains(imageRequest.Size, "×") {
			return nil, errors.New("size an unexpected error occurred in the parameter, please use 'x' instead of the multiplication sign '×'")
		}

		// Not "256x256", "512x512", or "1024x1024"
		if imageRequest.Model == "dall-e-2" || imageRequest.Model == "dall-e" {
			if imageRequest.Size != "" && imageRequest.Size != "256x256" && imageRequest.Size != "512x512" && imageRequest.Size != "1024x1024" {
				return nil, errors.New("size must be one of 256x256, 512x512, or 1024x1024 for dall-e-2 or dall-e")
			}
			if imageRequest.Size == "" {
				imageRequest.Size = "1024x1024"
			}
		} else if imageRequest.Model == "dall-e-3" {
			if imageRequest.Size != "" && imageRequest.Size != "1024x1024" && imageRequest.Size != "1024x1792" && imageRequest.Size != "1792x1024" {
				return nil, errors.New("size must be one of 1024x1024, 1024x1792 or 1792x1024 for dall-e-3")
			}
			if imageRequest.Quality == "" {
				imageRequest.Quality = "standard"
			}
			if imageRequest.Size == "" {
				imageRequest.Size = "1024x1024"
			}
		} else if imageRequest.Model == "gpt-image-1" {
			if imageRequest.Quality == "" {
				imageRequest.Quality = "auto"
			}
		}

		//if imageRequest.Prompt == "" {
		//	return nil, errors.New("prompt is required")
		//}

		if lo.FromPtrOr(imageRequest.N, 0) == 0 {
			imageRequest.N = lo.ToPtr(uint(1))
		}

		// Validate and normalize image parameter if present
		if len(imageRequest.Image) > 0 {
			var imageValue string
			if err := json.Unmarshal(imageRequest.Image, &imageValue); err == nil && imageValue != "" {
				// Check if it's a URL
				if strings.HasPrefix(imageValue, "http://") || strings.HasPrefix(imageValue, "https://") {
					// Validate URL format
					if !strings.Contains(imageValue, ".") {
						return nil, errors.New("image parameter contains invalid url: missing domain")
					}
					// Check for common URL issues
					if strings.Contains(imageValue, " ") {
						return nil, errors.New("image parameter contains invalid url: contains spaces")
					}
				} else if !strings.HasPrefix(imageValue, "data:") {
					// Not a URL and not a data URI, check if it's a valid base64 string
					// Base64 strings should only contain alphanumeric chars, +, /, = and have reasonable length
					if len(imageValue) < 100 {
						// Too short to be a valid image base64, likely an invalid path
						return nil, errors.New("image parameter must be a valid URL (http/https), base64 string, or data URI")
					}
					// Check if it looks like a file path or other invalid format
					if strings.Contains(imageValue, "/") || strings.Contains(imageValue, "\\") {
						// Contains path separators but not a URL
						if !strings.HasPrefix(imageValue, "iVBOR") && !strings.HasPrefix(imageValue, "/9j/") && !strings.HasPrefix(imageValue, "R0lGO") {
							return nil, errors.New("image parameter appears to be a file path, please use URL or base64 string")
						}
					}

					// Convert pure base64 to data URI format for compatibility
					// Detect image format based on base64 header
					var mimeType string
					if strings.HasPrefix(imageValue, "iVBOR") {
						mimeType = "image/png"
					} else if strings.HasPrefix(imageValue, "/9j/") {
						mimeType = "image/jpeg"
					} else if strings.HasPrefix(imageValue, "R0lGO") {
						mimeType = "image/gif"
					} else if strings.HasPrefix(imageValue, "UklGR") {
						mimeType = "image/webp"
					} else {
						// Default to PNG if cannot detect
						mimeType = "image/png"
					}

					// Convert to data URI format
					dataURI := fmt.Sprintf("data:%s;base64,%s", mimeType, imageValue)
					imageRequest.Image, _ = json.Marshal(dataURI)
				}
			}
		}
	}

	return imageRequest, nil
}

func GetAndValidateTextRequest(c gin.Context, relayMode int) (*dto.GeneralOpenAIRequest, error) {
	textRequest := &dto.GeneralOpenAIRequest{}
	err := common.UnmarshalBodyReusable(c, textRequest)
	if err != nil {
		return nil, err
	}

	if relayMode == relayconstant.RelayModeModerations && textRequest.Model == "" {
		textRequest.Model = "text-moderation-latest"
	}
	if relayMode == relayconstant.RelayModeEmbeddings && textRequest.Model == "" {
		textRequest.Model = c.Param("model")
	}

	if lo.FromPtrOr(textRequest.MaxTokens, 0) > math.MaxInt32/2 {
		return nil, errors.New("max_tokens is invalid")
	}
	if textRequest.Model == "" {
		return nil, errors.New("model is required")
	}
	if textRequest.WebSearchOptions != nil {
		if textRequest.WebSearchOptions.SearchContextSize != "" {
			validSizes := map[string]bool{
				"high":   true,
				"medium": true,
				"low":    true,
			}
			if !validSizes[textRequest.WebSearchOptions.SearchContextSize] {
				return nil, errors.New("invalid search_context_size, must be one of: high, medium, low")
			}
		} else {
			textRequest.WebSearchOptions.SearchContextSize = "medium"
		}
	}
	switch relayMode {
	case relayconstant.RelayModeCompletions:
		if textRequest.Prompt == "" {
			return nil, errors.New("field prompt is required")
		}
	case relayconstant.RelayModeChatCompletions:
		// For FIM (Fill-in-the-middle) requests with prefix/suffix, messages is optional
		// It will be filled by provider-specific adaptors if needed (e.g., SiliconFlow)。Or it is allowed by model vendor(s) (e.g., DeepSeek)
		if len(textRequest.Messages) == 0 && textRequest.Prefix == nil && textRequest.Suffix == nil {
			return nil, errors.New("field messages is required")
		}
	case relayconstant.RelayModeEmbeddings:
	case relayconstant.RelayModeModerations:
		if textRequest.Input == nil || textRequest.Input == "" {
			return nil, errors.New("field input is required")
		}
	case relayconstant.RelayModeEdits:
		if textRequest.Instruction == "" {
			return nil, errors.New("field instruction is required")
		}
	}
	return textRequest, nil
}
